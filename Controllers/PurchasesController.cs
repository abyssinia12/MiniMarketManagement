using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Rendering;
using Microsoft.EntityFrameworkCore;
using MiniMarket.Models;

namespace MiniMarket.Controllers
{
    public class PurchasesController : Controller
    {
        private readonly DBContext _context;

        public PurchasesController(DBContext context)
        {
            _context = context;
        }

        // GET: Purchases
        public async Task<IActionResult> Index()
        {
            var dBContext = _context.Purchases.Include(p => p.Product).Include(p => p.Supplier).Include(p => p.User);
            return View(await dBContext.ToListAsync());
        }

        // GET: Purchases/Details/5
        public async Task<IActionResult> Details(int? id)
        {
            if (id == null)
            {
                return NotFound();
            }

            var purchase = await _context.Purchases
                .Include(p => p.Product)
                .Include(p => p.Supplier)
                .Include(p => p.User)
                .FirstOrDefaultAsync(m => m.Id == id);
            if (purchase == null)
            {
                return NotFound();
            }

            return View(purchase);
        }

        // GET: Purchases/Create
        public IActionResult Create()
        {
            ViewData["ProductId"] = new SelectList(_context.Products, "Id", "Name");
            ViewData["SupplierId"] = new SelectList(_context.Suppliers, "Id", "Name");
            ViewData["UserId"] = new SelectList(_context.Users, "Id", "Username");
            return View();
        }

        // POST: Purchases/Create
        // To protect from overposting attacks, enable the specific properties you want to bind to.
        // For more details, see http://go.microsoft.com/fwlink/?LinkId=317598.
        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> Create([Bind("Id,SupplierId,UserId,ProductId,Quantity,UnitCost,AmountPaid")] Purchase purchase)
        {

            // Remove validation errors for properties
            // that are generated by the backend.
            ModelState.Remove(nameof(Purchase.PaymentStatus));
            ModelState.Remove(nameof(Purchase.Product));
            ModelState.Remove(nameof(Purchase.Supplier));
            ModelState.Remove(nameof(Purchase.User));

            // Calculate values before saving
            purchase.Subtotal = purchase.Quantity * purchase.UnitCost;
            purchase.TotalCost = purchase.Subtotal;

            // Assign payment status
            if (purchase.AmountPaid <= 0)
            {
                purchase.PaymentStatus = "Unpaid";
            }
            else if (purchase.AmountPaid >= purchase.TotalCost)
            {
                purchase.PaymentStatus = "Paid";
            }
            else
            {
                purchase.PaymentStatus = "Partial";
            }

            // Assign dates
            purchase.PurchaseDate = DateTime.Now;
            purchase.CreatedAt = DateTime.Now;

            // Default values
            purchase.IsActive = true;
            purchase.IsDelete = false;


            if (ModelState.IsValid)
            {
               
                _context.Purchases.Add(purchase);

                await _context.SaveChangesAsync();
                return RedirectToAction(nameof(Index));

            }

            // Display validation errors
            foreach (var error in ModelState.Values
                .SelectMany(v => v.Errors))
            {
                Console.WriteLine(error.ErrorMessage);
            }

            ViewData["ProductId"] = new SelectList(_context.Products.Where(c => c.IsActive && !c.IsDelete), "Id", "Name", purchase.ProductId);
            ViewData["SupplierId"] = new SelectList(_context.Suppliers.Where(c => c.IsActive && !c.IsDelete), "Id", "Name", purchase.SupplierId);
            ViewData["UserId"] = new SelectList(_context.Users.Where(c => c.IsActive && !c.IsDelete), "Id", "Username", purchase.UserId);
            return View(purchase);
        }
               

